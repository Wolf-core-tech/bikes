import 'bike_model.dart';

class BikeModelData {
  final String brand;
  final String modelName;
  final String vehicleType;
  final double? engineCC;
  final String? fuelType;
  final String? variant;
  final double? electricMotorPowerKW;
  final List<double> batteryCapacitiesKWh;

  const BikeModelData({
    required this.brand,
    required this.modelName,
    required this.vehicleType,
    this.engineCC,
    this.fuelType,
    this.variant,
    this.electricMotorPowerKW,
    this.batteryCapacitiesKWh = const [],
  });

  String get engineCCLabel {
    final cc = engineCC;
    if (cc == null) return 'Not available';
    final formatted = cc == cc.roundToDouble()
        ? cc.toStringAsFixed(0)
        : cc.toString();
    return '$formatted cc';
  }
}

